    private void saveBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_saveBtnActionPerformed
        
        if (canvas instanceof Canvas c) {
            Module top = c.getTopAsModule();
            if (top == null) {
                logger.log(Level.INFO, "Can't save empty canvas!");
                return;
            }
            
            JFileChooser jfc = new JFileChooser(lastModuleDir);
            jfc.setSelectedFile(new File(lastModuleDir, String.format("%s.yaml", top.getName())));
            if (jfc.showSaveDialog(saveBtn) == JFileChooser.APPROVE_OPTION) {
                lastModuleDir = jfc.getCurrentDirectory();
                
                YamlWriter writer = new YamlWriter();
                writer.writeModule(jfc.getSelectedFile(), top);
                c.modified = false;
            } 
        }
    }//GEN-LAST:event_saveBtnActionPerformed
    
