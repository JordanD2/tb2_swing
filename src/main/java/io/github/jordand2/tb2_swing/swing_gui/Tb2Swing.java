    private void renderBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_renderBtnActionPerformed
        if (canvas instanceof Canvas c) {
            
            Module top = c.getTopAsModule();
            if (top == null) {
                logger.log(Level.INFO, "Can't render empty canvas!");
                return;
            }
            
            JFileChooser jfc = new JFileChooser();
            jfc.setMultiSelectionEnabled(false);
            if (lastRenderDir != null) {
                jfc.setSelectedFile(lastRenderDir);
            }
            jfc.setFileSelectionMode(JFileChooser.DIRECTORIES_ONLY);
            jfc.setAcceptAllFileFilterUsed(false);

            if (jfc.showDialog(this, "Render!") == JFileChooser.APPROVE_OPTION) {
                ModuleRenderer moduleRenderer = new ModuleRenderer();
                String outputPath;
                if (jfc.getSelectedFile().isDirectory()) {
                    outputPath = jfc.getSelectedFile().getPath();
                } else {
                    outputPath = jfc.getSelectedFile().getParent();
                }
                try {
                    moduleRenderer.renderTopModule(top, outputPath);
                } catch (IOException ioe) {
                    logger.log(Level.SEVERE, String.format("Failed to write file '%s/%s.sv'!", outputPath, top.type));
                }
                lastRenderDir = new File(outputPath);
            } 
        }
    }//GEN-LAST:event_renderBtnActionPerformed

    private void formWindowClosing(java.awt.event.WindowEvent evt) {//GEN-FIRST:event_formWindowClosing
        logger.log(Level.INFO, "Closing window");
        
        if (canvas instanceof Canvas c && c.modified) {
            if (JOptionPane.showConfirmDialog(this, "Save before exit?", "", JOptionPane.YES_NO_OPTION) == JOptionPane.YES_OPTION) {
                saveBtnActionPerformed(new ActionEvent(evt.getSource(), ActionEvent.ACTION_PERFORMED, "Save"));
                
                if (c.modified) {
                    return; // cancel exit request
                }
            }
        }
        this.dispose();
        System.exit(0);
    }//GEN-LAST:event_formWindowClosing

