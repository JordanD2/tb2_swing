    private void okButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_okButtonActionPerformed
        if (portTarget != null) {
            moduleTarget = portTarget.parent;
            
            int selectedType;
            if (portRadButton.isSelected()) {
                selectedType = DrawPort.OUTPUT_PORT;
            } else {
                selectedType = DrawPort.INPUT_PORT;
            }
            
            if (portTarget.dataType.equals(dataTypeField.getText()) && portTarget.type == selectedType) {
                // Simple rename -> don't delete the connections
                portTarget.name = portNameField.getText();
            } else {
                // Changed dataType or direction -> delete and recreate the port
                moduleTarget.deletePort(portTarget);
                if (portTarget.type == selectedType) {
                    // Same direction -> preserve idx
                    moduleTarget.addPort(portNameField.getText(), dataTypeField.getText(), selectedType, portTarget.idx);
                } else {
                    // Changed direction -> reindex
                    moduleTarget.addPort(portNameField.getText(), dataTypeField.getText(), selectedType);
                }
            }
        } else {
            if (portRadButton.isSelected()) {
                moduleTarget.addPort(portNameField.getText(), dataTypeField.getText(), DrawPort.OUTPUT_PORT);
            } else {
                moduleTarget.addPort(portNameField.getText(), dataTypeField.getText(), DrawPort.INPUT_PORT);
            }
        }
        canvas.repaint();
        this.dispose();
    }//GEN-LAST:event_okButtonActionPerformed

