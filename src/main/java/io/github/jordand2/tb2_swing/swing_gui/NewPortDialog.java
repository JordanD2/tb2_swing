    public void usePortInfo(DrawPort port) {
        portNameField.setText(port.name);
        dataTypeField.setText(port.dataType);
        if (port.type == DrawPort.OUTPUT_PORT) {
            portRadButton.setSelected(true);
            exportRadButton.setSelected(false);
        } else {
            portRadButton.setSelected(false);
            exportRadButton.setSelected(true);
        }
    }

